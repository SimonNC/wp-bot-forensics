"""Build a small, pseudonymised, re-processable sample from one day of raw data."""

import csv
from datetime import date
from pathlib import Path

from botforensics.cerber import CERBER_HEADER, read_activity
from botforensics.config import Settings
from botforensics.geo import GeoLookup, IpInfo, write_sidecar
from botforensics.parse import format_time, open_text, parse_line
from botforensics.pipeline import require_secret_key
from botforensics.privacy import Redactor, pseudonymise, strip_query


def _quote(value: str | None) -> str:
    return (value or "-").replace("\\", "\\\\").replace('"', '\\"')


def make_sample(raw_dir: Path, day: str, out_dir: Path, settings: Settings) -> dict[str, int]:
    require_secret_key(settings)
    geo = GeoLookup(settings.asn_db, settings.country_db)
    redact = Redactor(settings.site_domain, settings.site_label, settings.custom_login_slug)
    key = settings.pseudo_key
    infos: dict[str, IpInfo] = {}

    def pseudo(ip: str) -> str:
        ip_hash = pseudonymise(ip, key)
        if ip_hash not in infos:
            infos[ip_hash] = geo.lookup(ip)
        return ip_hash

    (out_dir / "apache").mkdir(parents=True, exist_ok=True)
    (out_dir / "cerber").mkdir(parents=True, exist_ok=True)

    target = date.fromisoformat(day)
    n_requests = 0
    src = raw_dir / "apache" / f"access-{day}.log.gz"
    with open_text(src) as fh, (out_dir / "apache" / f"access-{day}.log").open(
            "w", encoding="utf-8", newline="\n") as out:
        for line in fh:
            r = parse_line(line)
            if r is None or r.timestamp.date() != target:
                continue
            path = redact(r.path)
            request = f"{r.method} {path} {r.protocol}" if r.method else path
            out.write(
                f'{pseudo(r.host)} - - [{format_time(r.timestamp)}] "{_quote(request)}" '
                f'{r.status} {r.size} "{_quote(strip_query(redact(r.referer)))}" '
                f'"{_quote(redact(r.user_agent))}"\n'
            )
            n_requests += 1

    rows = []
    for path in sorted((raw_dir / "cerber").glob("*activity*.csv")):
        raw = read_activity(path)
        for rec in raw[raw["timestamp"].dt.date == target].to_dict("records"):
            rows.append([
                pseudo(rec["ip"]),
                rec["event"],
                rec["status"],
                pseudonymise(rec["username"], key, prefix="user-") if rec["username"] else "",
                f"{rec['timestamp'].timestamp():.4f}",
                strip_query(redact(rec["url"])) or "",
            ])
    with (out_dir / "cerber" / f"activity-{day}.csv").open(
            "w", encoding="utf-8", newline="") as fh:
        writer = csv.writer(fh, quoting=csv.QUOTE_ALL)
        writer.writerow(["Generated by:", "wp-bot-forensics make-sample (pseudonymised)"])
        writer.writerow([])
        writer.writerow(CERBER_HEADER)
        writer.writerows(rows)

    write_sidecar(out_dir / "ip_info.csv", infos)
    return {"requests": n_requests, "cerber_events": len(rows), "ips": len(infos)}
