"""DuckDB analysis over the Parquet outputs → Markdown findings."""

import math
import re
from pathlib import Path

import duckdb
import numpy as np
import pandas as pd

from botforensics.rules import CATEGORIES

VIEWS = ("requests", "actors", "cerber_events")


def load_queries(path: Path) -> list[tuple[str, str, str]]:
    queries = []
    for block in re.split(r"(?m)^-- name:", path.read_text(encoding="utf-8"))[1:]:
        lines = block.strip().splitlines()
        name = lines[0].strip()
        if len(lines) < 2 or not lines[1].startswith("-- title:"):
            raise ValueError(f"query {name!r}: line 2 must start with '-- title:'")
        title = lines[1].removeprefix("-- title:").strip()
        queries.append((name, title, "\n".join(lines[2:]).strip()))
    return queries


def _cell(value) -> str:
    if isinstance(value, list | tuple | np.ndarray):  # list columns (e.g. reasons)
        return ", ".join(str(v) for v in value)
    return "" if value is None or pd.isna(value) else str(value)


def md_table(df: pd.DataFrame) -> str:
    lines = ["| " + " | ".join(df.columns) + " |", "|" + "---|" * len(df.columns)]
    lines += ["| " + " | ".join(_cell(v) for v in row) + " |" for row in df.itertuples(index=False)]
    return "\n".join(lines)


def _connect(processed: Path) -> duckdb.DuckDBPyConnection:
    con = duckdb.connect()
    con.execute("SET TimeZone = 'UTC'")
    for view in VIEWS:
        path = (processed / f"{view}.parquet").as_posix()
        con.execute(f"CREATE VIEW {view} AS SELECT * FROM read_parquet('{path}')")
    return con


def build_report(processed: Path, queries: Path) -> str:
    con = _connect(processed)
    parts = ["# Findings", "",
             f"Generated by `python -m botforensics report` from `{processed.as_posix()}`.", ""]
    for _, title, sql in load_queries(queries):
        parts += [f"## {title}", "", md_table(con.execute(sql).df()), ""]
    return "\n".join(parts)


def _has_labels(path: Path) -> bool:
    if not path.exists():
        return False
    df = pd.read_csv(path, dtype=str, keep_default_na=False)
    return "my_category" in df and bool((df["my_category"].str.strip() != "").any())


def write_review_sample(
    processed: Path, out: Path, n: int = 30, seed: int = 42, force: bool = False
) -> int:
    if not force and _has_labels(out):
        raise FileExistsError(f"{out} already holds my_category labels; use --force to overwrite")
    actors = pd.read_parquet(processed / "actors.parquet")
    pool = actors[actors["category"] != "internal"]
    per_cat = math.ceil(n / max(pool["category"].nunique(), 1))
    picked = pd.concat(
        [g.sample(n=min(per_cat, len(g)), random_state=seed) for _, g in pool.groupby("category")]
    )
    while len(picked) > n:  # rounding can overshoot: trim the best-represented category
        biggest = picked["category"].value_counts().index[0]
        picked = picked.drop(picked[picked["category"] == biggest].index[-1])
    rest = pool.drop(picked.index)
    top_up = rest.sample(n=min(n - len(picked), len(rest)), random_state=seed)
    sample = pd.concat([picked, top_up]).sort_values("category", kind="stable")
    cols = ["ip_hash", "category", "n_requests", "as_org", "top_user_agent", "iforest_outlier"]
    review = sample[cols].assign(reasons=sample["reasons"].map("; ".join), my_category="")
    review.to_csv(out, index=False)
    return len(review)


def review_agreement(path: Path) -> str | None:
    if not path.exists():
        return None
    df = pd.read_csv(path, dtype=str, keep_default_na=False)
    labels = df["my_category"].str.strip().str.lower()
    done = df.assign(label=labels)[labels != ""]
    if done.empty:
        return None
    invalid = done[~done["label"].isin(CATEGORIES)]
    valid = done[done["label"].isin(CATEGORIES)]
    agree = valid["label"] == valid["category"]
    lines = [
        f"Manual review: rules agree with the analyst on {int(agree.sum())}/{len(valid)} actors.",
        "",
        "The sample is stratified by rule category, so read agreement per category: it is the "
        "precision of each rule, not the overall accuracy of the classifier.",
        "",
        "| category | agree | reviewed |",
        "|---|---|---|",
    ]
    for cat in CATEGORIES:
        hits = agree[valid["category"] == cat]
        if len(hits):
            lines.append(f"| {cat} | {int(hits.sum())} | {len(hits)} |")
    if len(invalid):
        names = ", ".join(sorted(set(invalid["label"])))
        lines += ["", f"Invalid labels (not a category): {len(invalid)} ({names})"]
    return "\n".join(lines)
